// Headless browser checks: browser verification cases (V5, V16) and the scripted acceptance runs.
//
//   node tests/run-e2e.mjs [--headed] [--only v5|interior|bracket|shape|make|mesh|sweep|mobile|section|params|modes|convection] [--screens DIR]
//
// Starts a Vite dev server, drives Chromium with Playwright, writes docs/verification/V5.md,
// docs/verification/V16.md, docs/verification/bracket-e2e.md, docs/verification/mesh-e2e.md,
// docs/verification/sweep-e2e.md, docs/verification/mobile-e2e.md,
// docs/verification/V26.md (section-plane clip),
// docs/verification/V27.md (.fsm let-variables),
// docs/verification/V28.md (mode-shape animation), docs/verification/V29.md (Robin
// convection) and exits non-zero on any failure or
// console error.
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { bracketTest } from './bracket.mjs';
import { shapeTest } from './shape.mjs';
import { makeTest } from './make.mjs';
import { meshTest } from './mesh.mjs';
import { mobileTest } from './mobile.mjs';
import { interiorTest } from './interior.mjs';
import { sweepTest } from './sweep.mjs';
import { sectionTest } from './section.mjs';
import { paramsTest } from './params.mjs';
import { modesTest } from './modes.mjs';
import { convectionTest } from './convection.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const docsDir = resolve(root, '../docs/verification');
const args = process.argv.slice(2);
const headed = args.includes('--headed');
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;
const screens = args.includes('--screens') ? resolve(args[args.indexOf('--screens') + 1]) : resolve(root, 'test-results');
mkdirSync(docsDir, { recursive: true });
mkdirSync(screens, { recursive: true });

function pct(x) {
  return `${(x * 100).toFixed(3)} %`;
}

function v5Report(r) {
  const tol = 1e-4;
  const ok = !r.error && r.maxAbs <= tol;
  const lines = [
    '# V5 — Preview shader against the Rust evaluator',
    '',
    `**Result: ${ok ? 'PASS' : 'FAIL'}**`,
    '',
    '| Quantity | Reference | Measured | Tolerance | |',
    '| :-- | --: | --: | --: | :-- |',
  ];
  if (r.error) {
    lines.push(`| max \\|d_GPU − d_Rust\\| | 0 mm | error: ${r.error} | ${tol} mm | **fail** |`);
  } else {
    lines.push(`| max \\|d_GPU − d_Rust\\| over ${r.points} points | 0 mm | ${r.maxAbs.toExponential(3)} mm | ${tol} mm | ${ok ? 'pass' : '**fail**'} |`);
    lines.push('', '## Detail', '');
    lines.push(`- Renderer: ${r.renderer}`);
    lines.push(`- Sampling: ${r.spacingNote}, seeded (mulberry32, seed 5).`);
    lines.push(`- RMS difference: ${r.rms.toExponential(3)} mm; max within 2 mm of the surface: ${r.maxAbsNear.toExponential(3)} mm.`);
    lines.push(`- Largest gradient direction difference: ${r.maxGradAngleDeg.toExponential(3)}°.`);
    lines.push(`- Worst point (${r.worst.p.map((v) => v.toFixed(3)).join(', ')}) mm: GPU ${r.worst.gpu} mm, Rust ${r.worst.rust} mm.`);
  }
  lines.push(
    '',
    '## Method',
    '',
    'The bracket document (`examples/bracket.fsm`) is compiled once to GLSL (`fieldsmith_field::glsl`) and once to the Rust',
    'evaluator (`fieldsmith_field::expr::eval`, via WebAssembly). 10 000 random points are packed into an RGBA32F texture;',
    'a full-screen pass writes `fs_field(p)` for each point into an RGBA32F render target, which is read back and compared',
    'with the Rust value at the identical f32-rounded coordinates. The GPU computes in 32-bit floats, the Rust side in 64-bit;',
    'the tolerance therefore bounds codegen mistakes, not float precision.',
    '',
    '---',
    '*Generated by `npm run test:e2e` (web/tests/run-e2e.mjs) — do not edit by hand.*',
    '',
  );
  writeFileSync(resolve(docsDir, 'V5.md'), lines.join('\n'));
  return ok;
}

const server = await createServer({ root, logLevel: 'error', server: { port: 0, strictPort: false } });
await server.listen();
const url = server.resolvedUrls.local[0];
// Headless runs on the software rasteriser (that is what must stay portable); headed runs
// drive the machine's real GPU stack, mirroring probe-budgets.mjs's headed flags — window
// args keep the run fully on screen instead of floating off the top.
const launchArgs = headed
  ? {
      headless: false,
      channel: 'chrome',
      args: ['--use-angle=vulkan', '--no-sandbox', '--window-position=2280,300', '--window-size=1920,1100'],
    }
  : { headless: true, args: ['--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] };
let browser;
try {
  browser = await chromium.launch(launchArgs);
} catch {
  // No bundled Playwright browser: use the system Chrome.
  browser = await chromium.launch({ ...launchArgs, channel: 'chrome' });
}
let failed = false;
try {
  if (!only || only === 'v5') {
    const page = await browser.newPage();
    await page.goto(`${url}verify.html`);
    await page.waitForFunction(() => window.__verify, null, { timeout: 120000 });
    const res = await page.evaluate(() => window.__verify);
    const ok = v5Report(res.V5);
    console.log(`V5 ${ok ? 'PASS' : 'FAIL'}: max |Δd| = ${res.V5.maxAbs ?? res.V5.error}`);
    if (!ok) failed = true;
    await page.close();
  }
  if (!only || only === 'interior') {
    const ok = await interiorTest(browser, url, { screens, docsDir });
    console.log(`interior test ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'bracket') {
    const ok = await bracketTest(browser, url, { screens, docsDir, pct });
    console.log(`bracket test ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'shape') {
    const ok = await shapeTest(browser, url, { screens, docsDir });
    console.log(`shape lens ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'make') {
    const ok = await makeTest(browser, url, { screens, docsDir });
    console.log(`make lens ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'mesh') {
    const ok = await meshTest(browser, url, { screens, docsDir });
    console.log(`mesh test ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'sweep') {
    const ok = await sweepTest(browser, url, { screens, docsDir });
    console.log(`sweep lens ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'mobile') {
    const ok = await mobileTest(browser, url, { screens, docsDir });
    console.log(`mobile test ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'section') {
    const ok = await sectionTest(browser, url, { screens, docsDir });
    console.log(`section clip ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'params') {
    const ok = await paramsTest(browser, url, { screens, docsDir });
    console.log(`params test ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'modes') {
    const ok = await modesTest(browser, url, { screens, docsDir });
    console.log(`mode-shape animation ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
  if (!only || only === 'convection') {
    const ok = await convectionTest(browser, url, { screens, docsDir });
    console.log(`convection test ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }
} catch (e) {
  console.error(e);
  failed = true;
} finally {
  await browser.close();
  await server.close();
}
process.exit(failed ? 1 : 0);
