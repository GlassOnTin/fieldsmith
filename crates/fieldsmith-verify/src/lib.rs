//! Verification reports.
//!
//! Each verification case (V1–V9 in `GOAL.md`) is an integration test in `tests/` that computes
//! a value through the same code path the user sees, compares it with an independent reference,
//! and writes `docs/verification/Vn.md` with the measured error — *before* asserting, so a
//! failing case still leaves an honest report behind.

use std::fmt::Write as _;
use std::path::PathBuf;

pub mod coupon;

/// One compared quantity.
#[derive(Clone, Debug)]
pub struct Check {
    pub quantity: String,
    pub reference: f64,
    pub measured: f64,
    pub unit: String,
    /// Allowed relative error (e.g. 0.02 for 2 %), or absolute if `absolute` is set.
    pub tolerance: f64,
    pub absolute: bool,
}

impl Check {
    pub fn relative(
        quantity: &str,
        reference: f64,
        measured: f64,
        unit: &str,
        tolerance: f64,
    ) -> Self {
        Check {
            quantity: quantity.into(),
            reference,
            measured,
            unit: unit.into(),
            tolerance,
            absolute: false,
        }
    }
    pub fn absolute(
        quantity: &str,
        reference: f64,
        measured: f64,
        unit: &str,
        tolerance: f64,
    ) -> Self {
        Check {
            quantity: quantity.into(),
            reference,
            measured,
            unit: unit.into(),
            tolerance,
            absolute: true,
        }
    }
    pub fn error(&self) -> f64 {
        if self.absolute {
            (self.measured - self.reference).abs()
        } else {
            ((self.measured - self.reference) / self.reference).abs()
        }
    }
    pub fn passed(&self) -> bool {
        self.error() <= self.tolerance && self.measured.is_finite()
    }
}

/// A literate report: prose sections plus a table of checks.
pub struct Report {
    pub id: String,
    pub title: String,
    sections: Vec<(String, String)>,
    pub checks: Vec<Check>,
}

fn sig(x: f64) -> String {
    if x == 0.0 {
        return "0".into();
    }
    let a = x.abs();
    if (1e-3..1e6).contains(&a) {
        let digits = (6 - a.log10().floor() as i32).clamp(0, 9) as usize;
        format!("{x:.digits$}")
    } else {
        format!("{x:.4e}")
    }
}

/// Short form for tolerances: `0.5`, `2`, `1e-4`.
fn short(x: f64) -> String {
    let s = format!("{x}");
    if s.len() > 8 {
        format!("{x:e}")
    } else {
        s
    }
}

impl Report {
    pub fn new(id: &str, title: &str) -> Self {
        Report {
            id: id.into(),
            title: title.into(),
            sections: Vec::new(),
            checks: Vec::new(),
        }
    }

    pub fn section(&mut self, heading: &str, body: impl Into<String>) -> &mut Self {
        self.sections.push((heading.into(), body.into()));
        self
    }

    pub fn check(&mut self, c: Check) -> &mut Self {
        self.checks.push(c);
        self
    }

    pub fn passed(&self) -> bool {
        !self.checks.is_empty() && self.checks.iter().all(Check::passed)
    }

    pub fn markdown(&self) -> String {
        let mut s = String::new();
        let _ = writeln!(s, "# {} — {}\n", self.id, self.title);
        let _ = writeln!(
            s,
            "**Result: {}**\n",
            if self.passed() { "PASS" } else { "FAIL" }
        );
        let _ = writeln!(
            s,
            "| Quantity | Reference | Measured | Error | Tolerance | |"
        );
        let _ = writeln!(s, "| :-- | --: | --: | --: | --: | :-- |");
        for c in &self.checks {
            let (err, tol) = if c.absolute {
                (
                    format!("{} {}", sig(c.error()), c.unit),
                    format!("{} {}", short(c.tolerance), c.unit),
                )
            } else {
                (
                    format!("{:.3} %", c.error() * 100.0),
                    format!("{} %", short((c.tolerance * 1e6).round() / 1e4)),
                )
            };
            let _ = writeln!(
                s,
                "| {} | {} {} | {} {} | {} | {} | {} |",
                c.quantity,
                sig(c.reference),
                c.unit,
                sig(c.measured),
                c.unit,
                err,
                tol,
                if c.passed() { "pass" } else { "**fail**" }
            );
        }
        s.push('\n');
        for (h, b) in &self.sections {
            let _ = writeln!(s, "## {h}\n\n{}\n", b.trim_end());
        }
        let _ = writeln!(
            s,
            "---\n*Generated by `cargo test -p fieldsmith-verify` — do not edit by hand.*"
        );
        s
    }

    /// Write `docs/verification/<id>.md` (relative to the workspace root) and return the path.
    pub fn write(&self) -> PathBuf {
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        let dir = root.join("docs/verification");
        std::fs::create_dir_all(&dir).expect("create docs/verification");
        let path = dir.join(format!("{}.md", self.id));
        std::fs::write(&path, self.markdown()).expect("write report");
        path
    }

    /// Write the report, print it, then assert every check passed.
    pub fn finish(&self) {
        let path = self.write();
        println!("{}", self.markdown());
        println!("report: {}", path.display());
        for c in &self.checks {
            assert!(
                c.passed(),
                "{} {}: measured {} vs reference {} (error {:.4}, tolerance {})",
                self.id,
                c.quantity,
                c.measured,
                c.reference,
                c.error(),
                c.tolerance
            );
        }
    }
}

/// Load a document from the workspace `examples/` directory.
pub fn example(name: &str) -> fieldsmith_doc::Document {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../examples")
        .join(name);
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    fieldsmith_doc::fsm::parse(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

/// Parse an inline `.fsm` document.
pub fn doc(text: &str) -> fieldsmith_doc::Document {
    fieldsmith_doc::fsm::parse(&format!("fieldsmith 1\n{text}")).expect("valid test document")
}
